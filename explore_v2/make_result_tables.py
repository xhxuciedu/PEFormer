"""Generate the panel result's manuscript tables directly from the analysis artifacts.

Same discipline as `revision/make_paper_tables.py`: each table is a pure function of a JSON
written by a numbered script, and the manuscript `\\input`s the fragment rather than
carrying transcribed numbers, so a reported value cannot drift from the artifact that
produced it. `@name` substitution is used instead of f-strings so LaTeX braces and math
pass through untouched.

Run after E01, E02, E10 and E11:  .venv/bin/python explore_v2/make_result_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from string import Template

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _v2common as C  # noqa: E402

OUT = C.ROOT / "reports/paper/tables"


class LT(Template):
    delimiter = "@"


def load(stem: str) -> dict:
    return json.loads((C.OUT / f"{stem}.json").read_text())


def dig(o, path: str):
    for k in path.split("."):
        o = o[int(k)] if k.isdigit() else o[k]
    return o


def f(x: float, n: int = 4) -> str:
    return f"{x:.{n}f}"


def i(x) -> str:
    return f"{int(x):,}"


# --------------------------------------------------------------------------- #
TAB_DEPTH = LT(r"""% generated by explore_v2/make_result_tables.py -- do not edit
\begin{tabular}{lrrrrr}
\toprule
surface & rows & decision groups & $\ge 2$ & $\ge 3$ & $\ge 5$ \\
\midrule
\multicolumn{6}{l}{\footnotesize Groups are one intended allele in one experimental context;
the panel is defined as its $\ge 2$ groups, so its first two counts coincide.}\\
corpus (all folds) & @c_rows & @c_grp & @c_2 & @c_3 & @c_5 \\
held-out fold 0 & @h_rows & @h_grp & @h_2 & @h_3 & \textbf{@h_5} \\
reserved panel & @p_rows & @p_grp & @p_2 & @p_3 & \textbf{@p_5} \\
\bottomrule
\end{tabular}
""")

TAB_PANEL = LT(r"""% generated by explore_v2/make_result_tables.py -- do not edit
\begin{tabular}{lrrrrr}
\toprule
predictor & achieved @@1 & achieved @@3 & achieved @@5 & hit rate @@1 & regret @@1 \\
\midrule
\multicolumn{6}{l}{\footnotesize Each budget is scored on the groups with that many distinct
candidates (30,475 / 18,660 / 8,775); tied maxima receive full credit.}\\
random choice & @r1 & @r3 & @r5 & @rh & @rr \\
@op_row
PE-RankFormer (ordinal-S4D) & @o1 & @o3 & @o5 & @oh & @orr \\
\midrule
oracle over measured candidates & @orc & --- & --- & 1.0000 & 0.00000 \\
\bottomrule
\end{tabular}
""")

TAB_EFFORT = LT(r"""% generated by explore_v2/make_result_tables.py -- do not edit
\begin{tabular}{lrr}
\toprule
candidates tested & PE-RankFormer & random \\
\midrule
@rows
\bottomrule
\end{tabular}
""")


def main() -> None:
    e01, e10 = load("e01_decision_manifest"), load("e10_build_reserved_panel")
    # Endpoints come from E16, the recomputation through the tested `endpoints` module, not
    # from E11's inline code, whose candidate accounting, tie handling and degenerate-case
    # p-value were wrong (see e16_corrected_endpoints.md).
    e16 = load("e16_corrected_endpoints")
    e11 = load("e11_score_reserved_panel")
    OUT.mkdir(parents=True, exist_ok=True)

    a = e01["availability"]
    p = e10["panel"]
    (OUT / "tab_panel_depth.tex").write_text(TAB_DEPTH.substitute(
        c_rows=i(a["corpus"]["rows"]), c_grp=i(a["corpus"]["decision_groups"]),
        c_2=i(a["corpus"]["groups_ge_2"]), c_3=i(a["corpus"]["groups_ge_3"]),
        c_5=i(a["corpus"]["groups_ge_5"]),
        h_rows=i(a["fold0_heldout"]["rows"]), h_grp=i(a["fold0_heldout"]["decision_groups"]),
        h_2=i(a["fold0_heldout"]["groups_ge_2"]), h_3=i(a["fold0_heldout"]["groups_ge_3"]),
        h_5=i(a["fold0_heldout"]["groups_ge_5"]),
        p_rows=i(p["rows"]), p_grp=i(p["decision_groups"]),
        p_2=i(p["groups_ge_2"]), p_3=i(p["groups_ge_3"]), p_5=i(p["groups_ge_5"])))

    st = e16["strata"][0]
    ar = st["arms"]
    op_row = ""
    if "op" in ar:
        op_row = (r"OptiPrime & " + " & ".join(
            [f(ar["op"][f"achieved_at_{k}"]) for k in (1, 3, 5)]
            + [f(ar["op"]["hit_at_1"]), f(ar["op"]["regret_at_1"], 5)])
            + r" \\")
    (OUT / "tab_panel_endpoints.tex").write_text(TAB_PANEL.substitute(
        r1=f(ar["rand"]["achieved_at_1"]), r3=f(ar["rand"]["achieved_at_3"]),
        r5=f(ar["rand"]["achieved_at_5"]), rh=f(ar["rand"]["hit_at_1"]),
        rr=f(ar["rand"]["regret_at_1"], 5), op_row=op_row,
        o1=f(ar["ours"]["achieved_at_1"]), o3=f(ar["ours"]["achieved_at_3"]),
        o5=f(ar["ours"]["achieved_at_5"]), oh=f(ar["ours"]["hit_at_1"]),
        orr=f(ar["ours"]["regret_at_1"], 5), orc=f(st["oracle_all_groups"])))

    # No emphasis on either predictor: on this panel OptiPrime wins the decision endpoints,
    # so bolding "ours" by convention would misrepresent the table.
    se = e11["screening_effort"]
    cols = [c for c in ("ours", "rand") if c in se["curves"]]
    rows = "\n".join(
        f"{k} & " + " & ".join(f(se['curves'][c][j]) for c in cols) + r" \\"
        for j, k in enumerate(se["k"]))
    (OUT / "tab_panel_effort.tex").write_text(TAB_EFFORT.substitute(rows=rows))

    for name in ("tab_panel_depth", "tab_panel_endpoints", "tab_panel_effort"):
        print(f"wrote {OUT / (name + '.tex')}")


if __name__ == "__main__":
    main()
