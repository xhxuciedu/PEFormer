def tab_tierobust() -> None:
    d = load("task_1_3_tie_robust")
    ts, mm = d["tie_structure"], d["metrics"]
    keys = [("spearman", r"Spearman $\rhoS$"), ("kendall_tau_b", r"Kendall $\tau_b$"),
            ("auroc_edits_at_all", r"AUROC, edits at all"),
            ("spearman_editing_only", r"Spearman $\rhoS$, rows with $y>0$")]
    rows = []
    for pname, plab in (("all", "All"), ("Liu", "Liu"), ("Kim", "Kim")):
        e = mm[pname]
        rows.append(r"\multicolumn{5}{l}{\emph{" + plab +
                    f" ($n={e['n']:,}$, {100 * e['frac_zero']:.1f}" + r"\% zero)}} \\")
        for k, klab in keys:
            b = e.get("bootstrap", {}).get(k)
            cell = ci(b) if b and b["ci95"][0] == b["ci95"][0] else "{---}"
            rows.append(f"\\quad {klab} & {e['optiprime'][k]:.4f} & {e['ours'][k]:.4f} & "
                        f"{e['delta'][k]:+.4f} & {cell} \\\\")
    emit("tab_tierobust", TIEROBUST.substitute(
        rows="\n".join(rows), nours=f"{ts['ours']['n_distinct']:,}",
        nop=f"{ts['optiprime']['n_distinct']:,}",
        maxtie=f"{100 * max(ts['ours']['frac_in_largest_tie'], ts['optiprime']['frac_in_largest_tie']):.2f}",
        nboot=f"{mm['all']['bootstrap']['kendall_tau_b']['n_boot']:,}"))


