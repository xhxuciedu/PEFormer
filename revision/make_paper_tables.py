CALIB = LT(r"""\begin{table}[H]
\centering
\begin{threeparttable}
\caption{Absolute error against trivial floors, and behaviour in the high-efficiency
tail where absolute predictions matter for design.}
\label{tab:calibfloor}
\footnotesize
\begin{tabular}{l S[table-format=1.4] S[table-format=1.4] S[table-format=+1.4] c}
\toprule
Predictor & {MAE} & {RMSE} & {Bias} & {95\% CI on MAE} \\
\midrule
@rows
\midrule
\multicolumn{5}{l}{\emph{The calibrated model inside its own top-scoring slices}} \\
\quad top 5\% ($n=@n5$) & \multicolumn{4}{l}{predicts @p5, observes @o5 --- over-predicts by @g5} \\
\quad top 1\% ($n=@n1$) & \multicolumn{4}{l}{predicts @p1, observes @o1 --- over-predicts by @g1} \\
\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\footnotesize
\item Constant baselines are fitted on the 297{,}962 training rows only (median
@trmed, mean @trmean). The held-out mean (@homean) is an oracle floor no honest
predictor could use, and is shown only to bound the exercise.
\item The best trivial predictor reaches MAE @floor, so the calibrated model's @ourmae
is a @redpct\% reduction against that floor: the absolute error reflects skill rather
than the scale of a small-valued target.
\item \textbf{The isotonic map over-predicts its own tail.} A user told to expect
@p1short in the model's top percentile should expect @o1short. Isotonic regression has
the least data there and is monotone-constrained, so the final bin absorbs the whole
upper range. Ranking is unaffected \citep{zadrozny2002}; absolute predictions in the tail
should be read as optimistic, which is the regime where a design decision is most likely
to rest on the absolute number \citep{guo2017}.
\item Reproduce with \path{revision/task_1_5_calibration_baselines.py}.
\end{tablenotes}
\end{threeparttable}
\end{table}
""")


def tab_calibfloor() -> None:
    d = load("task_1_5_calibration_baselines")
    ae = d["absolute_error"]
    order = ["constant at training mean", "constant at training median",
             "constant at held-out mean (oracle floor)", "OptiPrime",
             "PE-RankFormer + isotonic"]
    rows = []
    for n in order:
        v = ae[n]
        b = r"\bfseries " if n.startswith("PE-RankFormer") else ""
        lo, hi = v["bootstrap_mae"]["ci95"]
        rows.append(f"{b}{n.replace('%', chr(92) + '%')} & {b}{v['mae']:.4f} & "
                    f"{b}{v['rmse']:.4f} & {v['bias']:+.4f} & "
                    f"$[{lo:.4f},\\,{hi:.4f}]$ \\\\")
    t5, t1 = d["top_5pct"], d["top_1pct"]
    floor = ae["constant at training median"]["mae"]
    ours = ae["PE-RankFormer + isotonic"]["mae"]
    emit("tab_calibfloor", CALIB.substitute(
        rows="\n".join(rows),
        n5=f"{t5['n']:,}", p5=f"{t5['mean_predicted']:.4f}",
        o5=f"{t5['mean_observed']:.4f}", g5=f"{t5['gap']:+.4f}",
        n1=f"{t1['n']:,}", p1=f"{t1['mean_predicted']:.4f}",
        o1=f"{t1['mean_observed']:.4f}", g1=f"{t1['gap']:+.4f}",
        p1short=f"{t1['mean_predicted']:.2f}", o1short=f"{t1['mean_observed']:.2f}",
        trmed=f"{d['training_median']:.4f}", trmean=f"{d['training_mean']:.4f}",
        homean=f"{d['heldout_mean']:.4f}", floor=f"{floor:.4f}", ourmae=f"{ours:.4f}",
        redpct=f"{100 * (1 - ours / floor):.0f}"))


