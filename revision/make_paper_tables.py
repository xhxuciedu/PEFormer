"""Generate the manuscript's result tables directly from the analysis artifacts.

Every table here is a pure function of a JSON file written by a numbered task script.
The manuscript `\\input`s the fragments rather than carrying transcribed numbers, so a
reported value cannot drift from the artifact that produced it. Two errors already found
in this manuscript -- a threshold count and a mislabelled fold -- were transcription
drift of exactly that kind.

Templates use `@name` substitution rather than f-strings, so LaTeX braces and math `$`
pass through untouched, and every value is formatted in Python before substitution.

Run after the Phase 1 tasks:  python revision/make_paper_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from string import Template

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

OUT = C.ROOT / "reports/paper/tables"
REV = C.ROOT / "revision"


class LT(Template):
    delimiter = "@"


def load(stem: str) -> dict:
    return json.loads((REV / f"{stem}.json").read_text())


def ci(d: dict, nd: int = 4, signed: bool = True) -> str:
    lo, hi = d["ci95"]
    f = f"+.{nd}f" if signed else f".{nd}f"
    return f"$[{lo:{f}},\\,{hi:{f}}]$"


def emit(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text(
        "% Generated by revision/make_paper_tables.py -- do not edit by hand.\n"
        "% Regenerate after re-running the Phase 1 task scripts.\n" + body)
    print(f"  reports/paper/tables/{name}.tex")


