CEILING = LT(r"""\begin{table}[H]
\centering
\begin{threeparttable}
\caption{Remaining headroom on the Kim partition against the replicate-based ceiling,
with the uncertainty the estimate carries.}
\label{tab:ceiling}
\footnotesize
\begin{tabular}{l S[table-format=5.0] S[table-format=1.4] S[table-format=1.4] c S[table-format=+1.4] c}
\toprule
Surface & {Rows} & {Model $\rhoS$} & {Ceiling} & {95\% CI, ceiling} & {Gap} & {95\% CI, gap} \\
\midrule
@rows
\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\footnotesize
\item Ceiling is $\sqrt{R}$ for replicate--replicate reliability $R$, estimated from
@ngroups groups in which all sixteen design and condition covariates and the target site
are identical (@npairs ordered pairs after symmetrisation). It depends only on the target
distribution of the row set and not on any model, which is why it differs between
surfaces.
\item Intervals resample the @ngroups replicate groups with replacement (@nboot
resamples). Estimator noise at a fixed group set has SD at most @estsd, an order of
magnitude smaller, so the uncertainty is dominated by how few replicate groups the
corpus contains rather than by the synthetic draw.
\item The headroom claim survives on every surface --- the lower bound of the gap stays
clear of zero --- but the interval is wide. ``Roughly $+0.10$'' is supportable; a third
decimal place is not, and an earlier draft quoted one.
\item Reproduce with \path{revision/task_1_6_ceiling_uncertainty.py}.
\end{tablenotes}
\end{threeparttable}
\end{table}
""")


def tab_ceiling() -> None:
    d = load("task_1_6_ceiling_uncertainty")
    sf = d["surfaces"]
    rows = []
    for k, lab in (("dev_fold_0", "Development fold 0"),
                   ("dev_fold_1", "Development fold 1"),
                   ("dev_fold_2", "Development fold 2"),
                   ("heldout", r"\textbf{Official held-out set}")):
        e = sf.get(k)
        if not e:
            continue
        lo, hi = e["ceiling_ci95_group_resample"]
        glo, ghi = e["gap_ci95"]
        rows.append(f"{lab} & {e['n_rows']:,} & {e['model']:.4f} & "
                    f"{e['ceiling_point']:.4f} & $[{lo:.4f},\\,{hi:.4f}]$ & "
                    f"{e['gap_point']:+.4f} & $[{glo:+.4f},\\,{ghi:+.4f}]$ \\\\")
    emit("tab_ceiling_uncertainty", CEILING.substitute(
        rows="\n".join(rows), ngroups=f"{d['n_replicate_groups']}",
        npairs=f"{d['n_ordered_pairs']:,}", nboot=f"{d['n_boot']}",
        estsd=f"{max(v['ceiling_sd_estimator_only'] for v in sf.values()):.4f}"))


def main() -> None:
    print("generating manuscript tables from analysis artifacts:")
    tab_stratified(); tab_utility(); tab_tierobust(); tab_leakage()
    tab_calibfloor(); tab_ceiling()
    print("\ninput these from the manuscript; do not transcribe their numbers.")




