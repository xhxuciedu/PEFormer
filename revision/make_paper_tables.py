UTILITY = LT(r"""\begin{table}[H]
\centering
\begin{threeparttable}
\caption{Deployment utility per target on the held-out set. A user selects designs for
one locus, so every metric is computed within a protospacer group and averaged over
groups.}
\label{tab:utility}
\footnotesize
\begin{tabular}{l S[table-format=1.3] S[table-format=1.3] S[table-format=1.3] S[table-format=+1.3] c}
\toprule
Metric & {Random} & {OptiPrime} & {PE-RankFormer} & {$\Delta$} & {95\% CI} \\
\midrule
@rows
\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\footnotesize
\item @ntargets targets carrying at least @mindesigns designs, covering @rowscov of the
20{,}509 held-out rows. Random selection is the exact expectation over the designs at
that target, except NDCG@@5 \citep{jarvelin2002} which averages 40 random
permutations. Precision@@$k$ is the overlap between the model's top $k$ designs and the
$k$ best-measured designs, divided by $k$; at $k=1$ it is the rate at which the model's
first pick is the target's best design.
\item Regret is in units of editing efficiency, so a negative $\Delta$ favours
PE-RankFormer on that row. Bold marks $p<0.05$ under a bootstrap over targets.
\item \textbf{The two rows that matter most for adoption disagree with the ranking
metrics.} PE-RankFormer identifies the single best design far more often (@p1ours
against @p1op, a @p1rel\% relative gain), but the efficiency actually obtained from its
top pick is only @effdelta better, and the probability that the top pick works at all
($\geq$5\%) is @ge5delta with an interval spanning zero. Both models' first picks are
usually already viable, so the gain is in finding the \emph{best} design rather than in
avoiding a failed one.
\item Reproduce with \path{revision/task_1_2_utility.py}.
\end{tablenotes}
\end{threeparttable}
\end{table}
""")


def tab_utility() -> None:
    d = load("task_1_2_utility")
    m = d["metrics"]
    labels = [("p_at_1", r"Precision@1"),
              ("p_at_5", r"Precision@5"), ("ndcg_at_5", r"NDCG@5"),
              ("top1_eff", r"Efficiency of the top pick"),
              ("regret", r"Regret vs.\ the best design"),
              ("top1_ge_0.05", r"Top pick reaches $\geq$5\% efficiency"),
              ("top1_ge_0.2", r"Top pick reaches $\geq$20\% efficiency")]
    rows = []
    for k, lab in labels:
        r, b = m[k], m[k]["ours_vs_optiprime"]
        bold = r"\bfseries " if b["two_sided_p"] < 0.05 else ""
        rows.append(f"{lab} & {r['random']:.3f} & {r['optiprime']:.3f} & "
                    f"{bold}{r['ours']:.3f} & {b['observed']:+.3f} & {ci(b, 3)} \\\\")
    p1 = m["p_at_1"]
    emit("tab_utility", UTILITY.substitute(
        rows="\n".join(rows), ntargets=f"{d['n_targets']}",
        mindesigns=f"{d['min_designs']}", rowscov=f"{d['rows_covered']:,}",
        p1ours=f"{p1['ours']:.3f}", p1op=f"{p1['optiprime']:.3f}",
        p1rel=f"{100 * (p1['ours'] / p1['optiprime'] - 1):.0f}",
        effdelta=f"{m['top1_eff']['ours_vs_optiprime']['observed']:+.3f}",
        ge5delta=f"{m['top1_ge_0.05']['ours_vs_optiprime']['observed']:+.3f}"))


